export const STORAGE_KEY = 'hospitality.locale'
export const LocaleContext = createContext(null)

export function normalizeLocale(value) {
  return value === 'sw' ? 'sw' : 'en'
}

export function localeTag(locale) {
  return locale === 'sw' ? 'sw-KE' : 'en-KE'
}

export function translate(locale, key, variables = {}) {
  const template = messages[locale]?.[key] ?? messages.en[key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? ''))
}

export function useI18n() {
  const value = useContext(LocaleContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
